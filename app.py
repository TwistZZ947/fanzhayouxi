@app.route('/')
def index():
    return render_template("index.html", total_level=len(question_data))

@app.route('/get_question/<int:level>')
def get_question(level):
    if 0 <= level < len(question_data):
        return jsonify(question_data[level])
    return jsonify({"err": "关卡不存在"}),400

@app.route('/check_ans', methods=["POST"])
def check_ans():
    data = request.get_json()
    lv = data["level"]
    user_ans = data["uans"]
    correct = question_data[lv]["ans"]
    return jsonify({"ok": user_ans == correct})

